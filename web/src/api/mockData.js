function withGeometry(f) {
  const w = Math.max(0.04, Math.sqrt(f.area_ha) / 900)
  const h = w * 0.7
  const geom = { rings: [ring(f.cx, f.cy, w, h)] }
  return {
    ...f,
    bxmin: f.cx - w,
    bymin: f.cy - h,
    bxmax: f.cx + w,
    bymax: f.cy + h,
    geometry: geom,
  }
}

export const MOCK_FORESTS = FORESTS_RAW.map(withGeometry)

function buildObs(forest) {
  if (!forest.last_obs_date) return []
  const out = []
  for (let i = 0; i < 18; i++) {
    const t = daysAgo(8 + i * 22 + (forest.unit_uid % 5))
    const cloudy = i % 7 === 3
    const wave = Math.sin(i / 3) * 0.04
    out.push({
      obs_id: `${forest.unit_id}_${i}`,
      unit_id: forest.unit_id,
      forest_name: forest.forest_name,
      forest_group: forest.forest_group,
      province: forest.province,
      district: forest.district,
      area_ha: forest.area_ha,
      obs_date: t,
      acq_day: new Date(t).toISOString().slice(0, 10),
      tiles: '36MUV',
      n_tiles: 1,
      tile_cloud_pct: cloudy ? 45 : 8,
      quality: cloudy ? 'Cloudy' : 'Valid',
      clear_pct: cloudy ? 35 : forest.clear_pct,
      coverage_pct: cloudy ? 70 : 95,
      ndvi: cloudy ? null : Number(((forest.ndvi || 0.5) + wave - i * 0.002).toFixed(3)),
      ndmi: cloudy ? null : Number(((forest.ndmi || 0.1) + wave * 0.5).toFixed(3)),
      nbr: cloudy ? null : Number(((forest.nbr || 0.3) + wave * 0.4 - (forest.nbr_drop || 0) * (i < 2 ? 0.3 : 0)).toFixed(3)),
      meaning: cloudy
        ? 'Too cloudy over this forest for a valid reading.'
        : `Valid Sentinel-2 observation for ${forest.forest_name}.`,
      run_id: 'mock',
      created_utc: t,
    })
  }
  return out
}

