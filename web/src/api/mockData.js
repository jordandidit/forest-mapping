function daysAgo(n) {
  const d = new Date()
  d.setDate(d.getDate() - n)
  return d.getTime()
}

function ring(cx, cy, w, h) {
  return [
    [cx - w, cy - h],
    [cx + w, cy - h],
    [cx + w, cy + h],
    [cx - w, cy + h],
    [cx - w, cy - h],
  ]
}

